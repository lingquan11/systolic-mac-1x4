#!/usr/bin/env python3
"""Build synth/synth_report.txt from the yosys outputs in synth/out/.

Inputs (written by synth/synth.ys, log by synth/run_synth.sh):
    out/systolic_row_synth.json   flattened gate-level netlist
    out/stat.txt                  yosys stat
    out/scc.txt                   yosys scc (logic-loop detection)
    out/check.txt                 yosys check -assert
    out/yosys.log                 full yosys log

Exit code 0 only if: no latch cells, no latch inferred in the log,
0 SCCs (no combinational loops), and check reported 0 problems.
"""

import collections
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "out")
TOP = "systolic_row"
N_PE = 4

# RTL registers and declared widths (rtl/mac_pe.v, rtl/systolic_row.v)
RTL_REGS = []
for j in range(N_PE):
    p = f"g_pe[{j}].u_pe."
    RTL_REGS += [(p + "w_reg", 8), (p + "x_out", 8),
                 (p + "psum_mid", 24), (p + "psum_out", 24)]
RTL_REGS += [("w_cnt", 2), ("x_valid_d", 1), ("vld_sr", 8),
             ("done", 1), ("y_out", 24)]

LATCH_RE = re.compile(r"^\$(_DLATCH|_DLATCHSR|_SR_|dlatch|adlatch|dlatchsr|sr$)")


def read(name):
    with open(os.path.join(OUT, name), encoding="utf-8", errors="replace") as f:
        return f.read()


def main():
    mod = json.loads(read("systolic_row_synth.json"))["modules"][TOP]
    cells = mod["cells"]
    nets = mod["netnames"]

    # ---- cell counts ------------------------------------------------------
    by_type = collections.Counter(c["type"] for c in cells.values())
    total = sum(by_type.values())
    meta = by_type.get("$scopeinfo", 0)          # hierarchy markers, no logic
    ff_types = {t: n for t, n in by_type.items() if "DFF" in t}
    n_ff = sum(ff_types.values())
    latch_types = {t: n for t, n in by_type.items() if LATCH_RE.match(t)}
    mem_types = {t: n for t, n in by_type.items() if t.startswith("$mem")}

    # ---- map every FF to its RTL register -------------------------------
    rtl_names = {n for n, _ in RTL_REGS}
    alias = collections.defaultdict(list)        # net bit id -> [(name, idx)]
    for n, d in nets.items():
        for i, b in enumerate(d["bits"]):
            if isinstance(b, int):
                alias[b].append((n, i))

    kept = collections.defaultdict(list)         # reg name -> [bit idx]
    ff_type_of = collections.defaultdict(collections.Counter)
    unmatched = []
    for cname, c in cells.items():
        if "DFF" not in c["type"]:
            continue
        q = c["connections"]["Q"][0]
        hit = [(n, i) for n, i in alias.get(q, []) if n in rtl_names]
        if not hit:
            unmatched.append(cname)
            continue
        n, i = hit[0]
        kept[n].append(i)
        ff_type_of[n][c["type"]] += 1

    # ---- loop / structural / latch-inference evidence --------------------
    scc_txt = read("scc.txt")
    m = re.search(r"Found (\d+) SCCs\.", scc_txt)
    n_scc = int(m.group(1)) if m else None
    chk_txt = read("check.txt")
    m = re.search(r"Found and reported (\d+) problems", chk_txt)
    n_problems = int(m.group(1)) if m else None
    log = read("yosys.log")
    latch_inferred = [l.strip() for l in log.splitlines()
                      if "Latch inferred for" in l and "No latch" not in l]
    # proc stage: how each RTL process register was implemented
    created = collections.Counter(re.findall(r"created \$(\w+) cell", log))
    n_proc_latch = sum(n for t, n in created.items() if "latch" in t or t == "sr")
    n_proc_ff = sum(n for t, n in created.items() if "dff" in t)
    n_warn = len(re.findall(r"^Warning:", log, flags=re.M))

    ok_latch = not latch_types and not latch_inferred and n_proc_latch == 0
    ok_loop = n_scc == 0
    ok_check = n_problems == 0

    # ---- report ----------------------------------------------------------
    L = []
    L.append("systolic_row -- yosys generic synthesis report")
    L.append("Generated by synth/run_synth.sh (synth/synth.ys + synth/make_report.py)")
    L.append("Flow: read_verilog rtl/mac_pe.v rtl/systolic_row.v; synth -flatten -top systolic_row")
    L.append("")
    L.append("1. Summary")
    L.append(f"   Total cells           : {total}  ({total - meta} logic/FF cells + {meta} $scopeinfo hierarchy markers)")
    L.append(f"   Flip-flops            : {n_ff}")
    L.append(f"   Latches               : {sum(latch_types.values())}")
    L.append(f"   Memories ($mem*)      : {sum(mem_types.values())}")
    L.append(f"   Combinational loops   : {n_scc} SCCs")
    L.append(f"   check -assert problems: {n_problems}")
    L.append(f"   yosys warnings        : {n_warn}")
    L.append("")
    L.append("2. Cell breakdown")
    for t, n in sorted(by_type.items()):
        L.append(f"   {t:<16} {n:6d}")
    L.append(f"   {'TOTAL':<16} {total:6d}")
    L.append("")
    L.append("3. Storage cells")
    L.append("   Flip-flop types:")
    desc = {"$_DFF_PN0_": "D flip-flop, async reset to 0 (active-low)",
            "$_DFFE_PN0P_": "D flip-flop with enable, async reset to 0 (active-low)"}
    for t, n in sorted(ff_types.items()):
        L.append(f"     {t:<14} {n:4d}  {desc.get(t, '')}")
    L.append(f"     {'TOTAL':<14} {n_ff:4d}")
    L.append("")
    L.append("   Per RTL register (RTL width vs flip-flops kept after synthesis):")
    L.append(f"     {'register':<26} {'RTL':>4} {'FF':>4} {'removed':>8}  kept bits  FF type / note")
    rtl_total = 0
    for n, w in RTL_REGS:
        rtl_total += w
        bits = sorted(kept.get(n, []))
        k = len(bits)
        rng = f"[{bits[-1]}:{bits[0]}]" if bits else "-"
        if k:
            note = ", ".join(f"{t} x{c}" for t, c in sorted(ff_type_of[n].items()))
        else:
            note = "removed entirely (output unused)" if n.endswith("x_out") else "removed entirely"
        L.append(f"     {n:<26} {w:4d} {k:4d} {w - k:8d}  {rng:<9}  {note}")
    L.append(f"     {'TOTAL':<26} {rtl_total:4d} {n_ff:4d} {rtl_total - n_ff:8d}")
    if unmatched:
        L.append(f"   WARNING: {len(unmatched)} flip-flop(s) not attributed to an RTL register")
    L.append("")
    L.append("   Why bits were removed:")
    L.append("   - psum_mid / psum_out / y_out: yosys width reduction proved the upper bits")
    L.append("     are always 0 (PE_j sum < 2^(16+j); full scale 4*255*255 = 260100 < 2^18).")
    L.append("     They are tied to constant 0; the 24-bit interface is unchanged.")
    L.append("   - g_pe[3].u_pe.x_out: last PE's x output drives nothing, so it was removed.")
    L.append("")
    L.append("4. Latch check")
    L.append(f"   Latch/SR cells in netlist ($_DLATCH*, $_SR_*, $dlatch, $adlatch, $sr): {sum(latch_types.values())}")
    L.append("   proc stage (RTL processes -> registers):")
    for t, n in sorted(created.items()):
        L.append(f"     created ${t:<10} {n:4d}")
    L.append(f"     latch/SR registers created: {n_proc_latch}  (flip-flop registers: {n_proc_ff})")
    L.append("     (counted per module before flattening: mac_pe is processed once, not per instance)")
    L.append("     All always blocks are clocked (posedge clk / negedge rst_n); there is no")
    L.append("     combinational always block, so proc_dlatch has nothing to infer a latch from.")
    L.append(f"   'Latch inferred' messages in yosys log                         : {len(latch_inferred)}")
    L.append("   select -assert-none on latch cell types (yosys stops if any)    : passed")
    L.append(f"   RESULT: {'NO LATCHES' if ok_latch else 'LATCH FOUND -- FAIL'}")
    L.append("")
    L.append("5. Combinational loop check")
    L.append(f"   yosys scc     : {scc_txt.strip().splitlines()[-1] if scc_txt.strip() else 'n/a'}")
    L.append(f"   yosys check   : Found and reported {n_problems} problems")
    L.append(f"   RESULT: {'NO COMBINATIONAL LOOPS' if ok_loop and ok_check else 'LOOP / CHECK PROBLEM -- FAIL'}")
    L.append("")
    L.append("6. Raw yosys stat")
    L += ["   " + l for l in read("stat.txt").strip().splitlines()]
    L.append("")

    report = "\n".join(L)
    path = os.path.join(HERE, "synth_report.txt")
    with open(path, "w", encoding="ascii", errors="replace", newline="\n") as f:
        f.write(report)
    print(report)
    print(f"wrote {path}")
    return 0 if (ok_latch and ok_loop and ok_check and not unmatched) else 1


if __name__ == "__main__":
    sys.exit(main())
