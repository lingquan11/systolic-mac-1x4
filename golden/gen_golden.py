#!/usr/bin/env python3
"""Generate golden inner-product cases for systolic_row.

Computes y = sum(w[i] * x[i]) for each case (unsigned), prints a table,
and writes a Verilog include file with the cases and expected results.

Deterministic: no randomness, no timestamps, fixed LF line endings, so
repeated runs produce byte-identical output.

Usage:
    python3 golden/gen_golden.py [output.vh]
Default output: golden_cases.vh next to this script.
"""

import os
import sys

DATA_W = 8
ACC_W = 24
N = 4

# (name, W, x)
CASES = [
    ("case0", [1, 2, 3, 4], [5, 6, 7, 8]),
    ("case1", [255, 255, 255, 255], [255, 255, 255, 255]),
    ("case2", [10, 0, 7, 3], [2, 9, 4, 1]),
    ("case3", [1, 1, 1, 1], [1, 1, 1, 1]),
]


def check_case(name, w, x):
    if len(w) != N or len(x) != N:
        raise ValueError(f"{name}: W and x must have {N} elements")
    for v in w + x:
        if not (isinstance(v, int) and 0 <= v < (1 << DATA_W)):
            raise ValueError(f"{name}: value {v!r} is not unsigned {DATA_W}-bit")


def dot(w, x):
    return sum(a * b for a, b in zip(w, x))


def concat(values, width):
    """Verilog concatenation, highest index first, so element i sits at
    bits [i*width +: width] of the packed vector."""
    return ", ".join(f"{width}'d{v}" for v in reversed(values))


def render_vh(results):
    nc = len(results)
    lines = [
        "// golden_cases.vh -- generated by golden/gen_golden.py, do not edit.",
        "// Include inside a module body, e.g. in the testbench:",
        "//   `include \"golden_cases.vh\"",
        "//",
        "// Indexing (c = case, i = element 0..3):",
        "//   w_i of case c : GOLD_W[(c*GOLD_N + i)*GOLD_DATA_W +: GOLD_DATA_W]",
        "//   x_i of case c : GOLD_X[(c*GOLD_N + i)*GOLD_DATA_W +: GOLD_DATA_W]",
        "//   expected y    : GOLD_Y[c*GOLD_ACC_W +: GOLD_ACC_W]",
        "//",
    ]
    for c, (name, w, x, y) in enumerate(results):
        lines.append(f"// {c}: {name}  W={w}  x={x}  y={y}")
    lines += [
        "",
        "`ifndef GOLDEN_CASES_VH",
        "`define GOLDEN_CASES_VH",
        "",
        f"localparam integer GOLD_NCASE  = {nc};",
        f"localparam integer GOLD_N      = {N};",
        f"localparam integer GOLD_DATA_W = {DATA_W};",
        f"localparam integer GOLD_ACC_W  = {ACC_W};",
        "",
    ]

    def packed(pname, width, rows):
        total = nc * len(rows[0]) * width if rows else 0
        out = [f"localparam [{total}-1:0] {pname} = {{"]
        # highest case first so case c is at the low-order position c
        for c in reversed(range(nc)):
            sep = "," if c > 0 else ""
            out.append(f"    {concat(rows[c], width)}{sep}  // {results[c][0]}")
        out.append("};")
        return out

    lines += packed("GOLD_W", DATA_W, [r[1] for r in results])
    lines.append("")
    lines += packed("GOLD_X", DATA_W, [r[2] for r in results])
    lines.append("")
    lines += packed("GOLD_Y", ACC_W, [[r[3]] for r in results])
    lines += ["", "`endif  // GOLDEN_CASES_VH", ""]
    return "\n".join(lines)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out_path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "golden_cases.vh")

    results = []
    for name, w, x in CASES:
        check_case(name, w, x)
        y = dot(w, x)
        if y >= (1 << ACC_W):
            raise ValueError(f"{name}: y={y} overflows {ACC_W} bits")
        results.append((name, w, x, y))

    print(f"{'case':<6} {'W':<22} {'x':<22} {'y':>8}")
    for name, w, x, y in results:
        print(f"{name:<6} {str(w):<22} {str(x):<22} {y:>8}")

    with open(out_path, "w", encoding="ascii", newline="\n") as f:
        f.write(render_vh(results))
    print(f"wrote {out_path}")


if __name__ == "__main__":
    main()
